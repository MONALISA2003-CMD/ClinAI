import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const api=read('services/api/src/routes/intelligenceCommandCenterRoutes.ts');
const main=read('services/api/src/main.ts');
const web=read('apps/web/app/page.tsx');
const component=read('apps/web/app/components/IntelligenceWorkspaces.tsx');
const css=read('apps/web/app/globals.css');
const migrationFiles=fs.readdirSync(path.join(root,'database/migrations')).filter(x=>x.endsWith('.sql')).sort();
const aiFiles=['services/api/src/ai/ai-orchestrator.ts','services/api/src/ai/ai-providers.ts','services/intelligence/clinical_reasoning.py'];
const expectedWorkspaces=['patient-360','clinical-velocity','value-based-care','ai-risk','ai-security','ai-governance','ai-evaluations','care-gaps','district-intelligence'];
const checks=[];
function ok(name,pass,detail=''){checks.push({name,pass,detail});}
ok('Phase10 route registered',main.includes('registerPhase1011Routes(app,pool'),main.match(/registerPhase1011Routes/g)?.length||0);
ok('Phase11 home route exists',api.includes("app.get('/api/phase11/home'"));
ok('Phase10 workspace route exists',api.includes("app.get('/api/phase10/intelligence/:workspace'"));
ok('Phase10 action route exists',api.includes("app.post('/api/phase10/intelligence/:workspace/action'"));
ok('All Phase10 workspaces mapped',expectedWorkspaces.every(x=>api.includes(`'${x}'`)));
ok('Phase10 frontend component wired',web.includes("from './components/Phase1011'")&&web.includes('<Phase10Workspace')&&web.includes('<Phase11CommandCenter'));
ok('Home uses Phase11 Command Center',web.includes("module==='command-center'?<Phase11CommandCenter"));
ok('Patient 360 evidence sources',component.includes('c.diagnoses')&&component.includes('c.laboratory')&&component.includes('c.medications')&&component.includes('data.careGaps'));
ok('Clinical velocity timestamps',api.includes('Door to provider')&&api.includes('Lab turnaround')&&api.includes('Imaging turnaround')&&api.includes('Referral turnaround')&&api.includes('Medication turnaround')&&api.includes('Discharge turnaround'));
ok('AI Frontline source is clinical_signals',api.includes('FROM clinical_signals WHERE organization_id=$1')&&api.includes('aiFrontline:frontline.rows'));
ok('Home operational flow connected',api.includes("('Registration'" )&&api.includes("('Pharmacy'" )&&api.includes("('Discharge'"));
ok('Care gap workflow actions',api.includes("workspace==='care-gaps'")&&api.includes("status=b.action==='resolve'"));
ok('Clinical signal human review action',api.includes('clinical_signal_actions')&&api.includes('acknowledged_by'));
ok('AI evaluation authoritative table',api.includes('FROM ai_evaluations')&&api.includes("workspace==='ai-evaluations'"));
ok('District intelligence authoritative sources',api.includes('FROM districts')&&api.includes('FROM population_indicators')&&api.includes('district_facility_links'));
ok('Reusable visualization system',component.includes('function BarList')&&component.includes('function Trend')&&css.includes('.p1011-bars')&&css.includes('.p1011-trend'));
const aiHashes=['075b0c9535f9d0071da585ab1026b5c6b1c7d049bdd0a65e38d85debb6f150b4','9262acea258a7d8a2eeaa71f4b2f7a417f458f31ddb5d697cdccacb535554af9','71cb4f55bf33bfa3888ac31aad3019499af2d96a32d0ade1ee74a69b7b19577b'];
const crypto=await import('node:crypto');
const currentHashes=aiFiles.map(f=>crypto.createHash('sha256').update(fs.readFileSync(path.join(root,f))).digest('hex'));
ok('AI response/orchestration files preserved byte-for-byte',currentHashes.every((h,i)=>h===aiHashes[i]),currentHashes.join(','));
const destructive=[];
const phaseFiles=migrationFiles.filter(f=>f.includes('phase10')||f.includes('phase11'));
for(const f of phaseFiles){const s=read(`database/migrations/${f}`);if(/\b(DROP\s+TABLE|TRUNCATE\b|DROP\s+SCHEMA)\b/i.test(s))destructive.push(f);}
ok('No destructive Phase10/11 migrations',destructive.length===0,destructive.join(','));
ok('Responsive Phase10/11 CSS',css.includes('@media(max-width:700px)')&&css.includes('.p1011-grid-2'));
const failed=checks.filter(x=>!x.pass);
console.log(JSON.stringify({ok:failed.length===0,phase10to11:true,checks,failed:failed.length},null,2));
if(failed.length)process.exit(1);
