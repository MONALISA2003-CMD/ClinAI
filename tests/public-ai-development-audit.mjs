import fs from 'node:fs';
import assert from 'node:assert/strict';
const api=fs.readFileSync('services/api/src/ai/ai-orchestrator.ts','utf8');
const main=fs.readFileSync('services/api/src/main.ts','utf8');
const web=fs.readFileSync('apps/web/app/page.tsx','utf8');
assert.ok(main.includes("'/api/public/ai-assist'"),'public AI route is not public-path allowlisted');
assert.ok(api.includes("app.post('/api/public/ai-assist'"),'public AI route missing');
assert.ok(api.includes("publicMode: true"),'public AI must use public mode');
assert.ok(api.includes('testPatientNumber') && api.includes('publicTestPatient'),'public AI must support the synthetic test patient boundary');
assert.ok(api.includes('is_test_data=true'),'public AI must resolve only synthetic test patients');
assert.ok(api.includes("allowCodeExecution: false"),'public AI must not enable code execution');
assert.ok(api.includes("t.name === 'calculate' || t.name === 'analyze_dataset'"),'public tool allowlist missing');
assert.ok(web.includes('publicMode={!token}'),'web must expose public AI when no session exists');
assert.ok(web.includes('/api/public/ai-assist'),'web must call the public AI endpoint');
assert.ok(web.includes('/api/public/ai-feedback'),'web must collect anonymous AI feedback');
assert.ok(web.includes('Add synthetic media'),'public multimodal testing control missing');
assert.ok(web.includes('value="medical"'),'public healthcare reasoning capability missing');
assert.ok(api.includes("'malaria'") && api.includes("'treatment'"),'public healthcare scope coverage missing');
for (const mode of ['quick','intelligence','analysis','research']) assert.ok(web.includes(`['${mode}'`),`public mode ${mode} missing`);
console.log('ClinAI public AI development audit passed.');
