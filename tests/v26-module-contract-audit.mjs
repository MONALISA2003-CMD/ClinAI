import fs from 'node:fs';
import assert from 'node:assert/strict';
const web=fs.readFileSync(new URL('../apps/web/app/page.tsx',import.meta.url),'utf8');
const api=fs.readFileSync(new URL('../services/api/src/main.ts',import.meta.url),'utf8');
const groupsBlock=web.match(/const groups:any\[\]=\[(.*?)\n\];/s)?.[1]||'';
const frontend=[...groupsBlock.matchAll(/'([a-z0-9-]+)'/g)].map(m=>m[1]);
const backend=api.match(/const modules = \[(.*?)\] as const;/s)?.[1]||'';
const backendModules=[...backend.matchAll(/'([a-z0-9-]+)'/g)].map(m=>m[1]);
const readMap=web.match(/const MODULE_READ_ENDPOINTS:Record<string,string>=\{(.*?)\n\};/s)?.[1]||'';
const createMap=web.match(/const MODULE_CREATE_ENDPOINTS:Record<string,string>=\{(.*?)\n\};/s)?.[1]||'';
const readOnly=web.match(/const MODULE_READ_ONLY=new Set\(\[(.*?)\]\);/s)?.[1]||'';
const readKeys=[...readMap.matchAll(/(?:'([a-z0-9-]+)'|([a-z0-9-]+))\s*:/g)].map(m=>m[1]||m[2]);
const createKeys=[...createMap.matchAll(/(?:'([a-z0-9-]+)'|([a-z0-9-]+))\s*:/g)].map(m=>m[1]||m[2]);
const roKeys=[...readOnly.matchAll(/'([a-z0-9-]+)'/g)].map(m=>m[1]);
const missing=frontend.filter(x=>!backendModules.includes(x)&&!readKeys.includes(x));
assert.deepEqual(missing,[],`Frontend modules without backend contract: ${missing.join(', ')}`);
const noWrite=frontend.filter(x=>!backendModules.includes(x)&&!createKeys.includes(x)&&!roKeys.includes(x));
assert.deepEqual(noWrite,[],`Specialized modules need create contract or explicit read-only state: ${noWrite.join(', ')}`);
for(const x of ['referral-transfers','care-tasks','child-health','medication-reconciliation','consents','portal-messages','surveillance','investigations','response','mortality','district-intelligence','facility-capacity','facility-resources','facility-incidents','facility-performance','referral-network','ai-evaluations','care-graph']) assert.ok(readKeys.includes(x),`${x} missing read endpoint mapping`);
assert.ok(api.includes("app.get('/api/referral-transfers'"));
assert.ok(api.includes("app.get('/api/care-tasks'"));
assert.ok(api.includes("app.get('/api/child-health'"));
assert.ok(api.includes("app.get('/api/medication-reconciliation'"));
assert.ok(api.includes("app.get('/api/consents'"));
assert.ok(api.includes("app.get('/api/portal-messages'"));
assert.ok(api.includes("app.get('/api/surveillance'"));
assert.ok(api.includes("app.get('/api/investigations'"));
assert.ok(api.includes("app.get('/api/response'"));
assert.ok(api.includes("app.get('/api/mortality'"));
assert.ok(api.includes("app.get('/api/district-intelligence'"));
assert.ok(api.includes("app.get('/api/facility-capacity'"));
assert.ok(api.includes("app.get('/api/facility-resources'"));
assert.ok(api.includes("app.get('/api/facility-performance'"));
assert.ok(api.includes("app.get('/api/referral-network'"));
assert.ok(api.includes("app.get('/api/ai-evaluations'"));
assert.ok(api.includes("app.get('/api/care-graph'"));
assert.ok(api.includes("AUTHENTICATION_REQUIRED"));
console.log(`V26 module contract audit passed: ${frontend.length} frontend modules checked.`);
